def source_for(num):
    blob = io.open(os.path.join(HERE, "source.md"), encoding="utf-8").read()
    m = re.search(r"^#### %s\..*?(?=^#{3,4} |\Z)" % re.escape(num), blob, re.S | re.M)
    if not m:
        raise SystemExit("нет исходного текста для %s" % num)
    return m.group(0).strip()


