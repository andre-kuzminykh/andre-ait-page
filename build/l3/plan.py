def source_for(n):
    blob = io.open(os.path.join(HERE, "source.md"), encoding="utf-8").read()
    m = re.search(r"^## %d\..*?(?=^## |\Z)" % n, blob, re.S | re.M)
    if not m:
        raise SystemExit("нет исходного текста для %d" % n)
    return m.group(0).strip()


def plain(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s)).strip()


def heading(sid, t1, t2):
    if sid == 0:
        return (u"## Заголовок обложки (вставить дословно, это h1)\n\n```html\n"
                u'<h1 class="text-2xl sm:text-4xl md:text-5xl lg:text-[60px] font-black mb-2 md:mb-6 leading-tight tracking-tight text-black">\n'
                u'                %s <span class="text-solar">%s</span>\n            </h1>\n```\n') % (t1, t2)
    if sid == 41:
        return (u"## Заголовок (вставить дословно)\n\n```html\n"
                u'<h2 class="text-xl sm:text-3xl md:text-5xl font-black mb-3 md:mb-5 text-center text-white"><span class="text-solar">%s</span></h2>\n```\n') % t1
    return (u"## Заголовок (вставить дословно — это заголовок владельца из его текста)\n\n```html\n"
            u'<h2 class="text-xl sm:text-3xl md:text-5xl font-black mb-3 md:mb-5 text-center text-black">%s <span class="text-solar">%s</span></h2>\n```\n') % (t1, t2)


