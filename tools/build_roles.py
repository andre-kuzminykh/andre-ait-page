# Владелец: «ты просто бросаешь инфографику — надо чтобы она оставалась,
# пока не появляется новая». Между сценами оставались дыры (0.1…0.7 c,
# всего 5.1 c на ролик), и в них кадр пустел: сцена гаснет за 0.55 c, а
# следующая приходит только через полсекунды.
#
# Поэтому data-out сцены ставится РАВНЫМ data-in следующей: старая уходит
# ровно тогда, когда приходит новая, и пустого кадра не остаётся вовсе.
# Числа сцен из раскладки при этом не трогаются — правится только конец.
# У последней сцены конец остаётся своим: дальше по замыслу одна шапка.
ДОРОЖКА = "101.8"
ТЕГ = re.compile(r'(<section class="scene" id="(\w+)" data-in="([\d.]+)" data-out=")([\d.]+)(")')
времена = []
for сцена in L:
    m = ТЕГ.search(сцена)
    assert m, "у сцены не разобрались data-in/data-out"
    времена.append((m.group(2), m.group(3), m.group(4)))


def досюда(i, конец):
    """Дотянуть конец i-й сцены до `конец` — правится только это число."""
    было = L[i]
    L[i] = ТЕГ.sub(lambda m: m.group(1) + конец + m.group(5), было, count=1)
    assert L[i] != было, "конец сцены %s не переписался" % времена[i][0]


for i in range(len(L) - 1):
    ид, нач, кон = времена[i]
    след = времена[i + 1][1]
    assert float(след) > float(нач), "сцены идут не по порядку: %s" % ид
    if float(след) > float(кон) + 1e-6:
        досюда(i, след)
# последняя доживает до конца речи, дальше в слое остаётся одна шапка
