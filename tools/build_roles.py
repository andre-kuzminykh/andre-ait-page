def кольцо(sid, in_, out_, центр, шаги, комментарий=""):
    """Шесть этапов кружками по ровному кругу вокруг агента."""
    assert len(шаги) == len(ЦИКЛ), "в кольце должно быть шесть этапов"
    т = ['        <!-- ══ %s ══ -->\n' % (комментарий or sid),
         '        <section class="scene" id="%s" data-in="%s" data-out="%s">\n' % (sid, in_, out_),
         '            <div class="cycle">\n',
         '                <div class="hub el" data-in="%s">'
         '<div class="halo"><div class="glow"></div></div>'
         '<div class="agent">%s</div></div>\n' % (центр[0], ico(центр[1]))]
    for (x, y, где), ш in zip(ЦИКЛ, шаги):
        кружок = item(ш[0], ш[1], ш[2], 72, ш[3], cur=ш[4]).strip()
        if где == "t":
            стиль, класс = 'left:%dpx;bottom:%dpx' % (x, ВЫСОТА - y - 36), "pos t"
        elif где == "b":
            стиль, класс = 'left:%dpx;top:%dpx' % (x, y - 36), "pos b"
        elif где == "r":
            стиль, класс = 'left:%dpx;top:%dpx' % (x - 36, y - 36), "pos side r"
        else:
            стиль, класс = 'right:%dpx;top:%dpx' % (ГОРИЗОНТ - x - 36, y - 36), "pos side l"
        т.append('                <div class="%s" style="%s">%s</div>\n' % (класс, стиль, кружок))
    т.append('            </div>\n        </section>\n\n')
    return "".join(т)


КЕГЛЬ_КАРТОЧКИ, ЗАЗОР_КАРТОЧЕК = 28, 40


def колонка(подписи, кегль=КЕГЛЬ_КАРТОЧКИ, зазор_букв=26, минимум=200):
    """Ширина колонки ряда иконок — по самим подписям, а не на глаз.

    Считаем шаг между центрами так, чтобы у любой соседней пары остался
    зазор, и проверяем, что крайние подписи не выходят к краю кадра.
    """
    if len(подписи) < 2:
        return int(max(минимум, ШРИФТ.ширина(подписи[0], кегль))) - ЗАЗОР_КАРТОЧЕК
    w = [ШРИФТ.ширина(т.replace("&amp;", "&"), кегль) for т in подписи]
    шаг = max(минимум, max((w[i] + w[i + 1]) / 2.0 + зазор_букв for i in range(len(w) - 1)))
    поле = 540 - шаг * (len(w) - 1) / 2.0 - max(w[0], w[-1]) / 2.0
    assert поле >= 60, "ряд иконок не влезает в кадр: %r (поле %d)" % (подписи, поле)
    return int(round(шаг)) - ЗАЗОР_КАРТОЧЕК


КОЛОНКИ = []           # (id сцены, ширина) — из них потом соберём CSS


def ряд(sid, in_, out_, элементы, шапка="", подвал="", пара=False, комментарий=""):
    """Перечисление кружками с иконками: заголовок строкой и ряд иконок.

    ДВА элемента — это всегда пара над картинами, а не ряд посередине.
    Владелец: «иконки, когда их две, на одном расстоянии должно быть как
    „процессы / структура“ на первом кадре или „бизнес / экономика“».
    В кадре между ними голова, поэтому середина обязана быть свободна —
    ряд из двух сдвигал обе иконки в центр, прямо на говорящего.
    Правило держится здесь, а не в вызовах: забыть его нельзя.
    """
    if len(элементы) == 2:
        пара = True
    подписи = [э[3] for э in элементы]
    if not пара:            # у пары ширину держит .row.duo, своя колонка ей мешает
        КОЛОНКИ.append((sid, колонка(подписи)))
    один = len(элементы) == 1
    размер = 132 if один else (108 if пара else 104)
    строки = "".join(
        item(э[0], э[1], э[2], размер, э[3], cur=э[4],
             halo=('<div class="halo el" data-in="%s"><div class="glow %s"></div></div>'
                   % (э[0], "glow-ember" if э[2] == "ember" else "")) if один else "")
        for э in элементы)
    шапка_html = шапка if шапка.startswith("            <div") or not шапка else cores(шапка)
    т = ['        <!-- ══ %s ══ -->\n' % (комментарий or sid),
         '        <section class="scene" id="%s" data-in="%s" data-out="%s">\n' % (sid, in_, out_),
         '            <div class="cards%s">\n' % (" one" if len(элементы) == 1 else ""),
         шапка_html,
         '            <div class="row%s">\n%s            </div>\n' % (" duo" if пара else "", строки),
         подвал if not подвал or подвал.startswith("            <div") else cores(подвал),
         '            </div>\n        </section>\n\n']
    return "".join(т)


