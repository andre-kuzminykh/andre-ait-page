# Причина не в таймингах, а в покадровом рендере. __renderAt перематывает
# каждый переход на (time − start), и start всегда брался из data-in. Для
# УХОДА это число в разы больше длины перехода (сцена началась 4.7 c
# назад, а переход длится 0.55 c), поэтому переход прыгал в конец, и
# графика пропадала ЗА ОДИН КАДР. Замер по готовому слою: на 50.57
# средняя альфа падает 114.8 → 104.3 за 1/30 секунды.
