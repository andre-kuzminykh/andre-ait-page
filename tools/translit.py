_COMPILED = [(re.compile(p), r) for p, r in RULES]


# ── Применение с сохранением разметки `**жирный**` ────────────────────────

def _split_bold(s):
    """`**жирный**` → чистый текст + список диапазонов выделения."""
    parts, ranges, i, opened = [], [], 0, None
    while True:
        j = s.find('**', i)
        if j < 0:
            parts.append(s[i:])
            break
        parts.append(s[i:j])
        i = j + 2
        pos = sum(len(p) for p in parts)
        if opened is None:
            opened = pos
        else:
            ranges.append((opened, pos))
            opened = None
    if opened is not None:          # непарная `**` — оставляем как есть
        return s, None
    return ''.join(parts), ranges


def _join_bold(text, ranges):
    if not ranges:
        return text
    out, last = [], 0
    for a, b in ranges:
        if a >= b:                  # выделение схлопнулось после замены
            continue
        out.append(text[last:a]); out.append('**')
        out.append(text[a:b]); out.append('**')
        last = b
    out.append(text[last:])
    return ''.join(out)


ANCHOR = '\x03'   # в замене отмечает слова, на которые переносится `**жирный**`


def _sub_tracked(rx, rep, text, ranges):
    """Замена с переносом границ `**жирного**` на новые позиции.

    Если выделение целиком попало внутрь заменяемого куска, оно переезжает на
    отмеченные `ANCHOR`-ом слова замены, а если разметки нет — на всю замену.
    Без этого жирный просто схлопывался и терялся.
    """
    edits = []
    for m in rx.finditer(text):
        raw = m.expand(rep)
        i1 = raw.find(ANCHOR)
        i2 = raw.find(ANCHOR, i1 + 1) if i1 >= 0 else -1
        nt = raw.replace(ANCHOR, '')
        span = (i1, i2 - 1) if i2 > i1 >= 0 else (0, len(nt))
        edits.append((m.start(), m.end(), nt, span))
    if not edits:
        return text, ranges
    out, last = [], 0
    for a, b, nt, _ in edits:
        out.append(text[last:a]); out.append(nt); last = b
    out.append(text[last:])
    new_text = ''.join(out)

    def remap(p, is_start):
        d = 0
        for a, b, nt, span in edits:
            if b <= p:
                d += len(nt) - (b - a)
            elif a < p:                     # точка внутри замены — к якорю
                return a + d + (span[0] if is_start else span[1])
        return p + d

    return new_text, [(remap(a, True), remap(b, False)) for a, b in ranges]


# `\bAI\b` ловит и «AI-агент» (дефис — не словесный символ), поэтому правило одно.
# Отрицательный просмотр вперёд нужен из-за замен выше: правило может САМО породить
# «AI-First», и без него оно тут же превратило бы его в «ИИ-First».
_AI_RULES = [(re.compile(r'\bAI\b(?!-(?:First|first|Native|native|Driven|driven|powered))'), 'ИИ')]


# Написание имён приводим к тому виду, что на слайдах: заказчик отдельно просил
# «AI-First», а книга местами писала «AI-first».
_CASE = ((r'AI-first\b', 'AI-First'), (r'AI-native\b', 'AI-Native'),
         (r'AI-driven\b', 'AI-Driven'))


def translate(s):
    """Полный перевод строки: термины + AI→ИИ, с сохранением `**жирного**`."""
    for pat, rep in _CASE:
        s = re.sub(pat, rep, s)
    protected, saved = _protect(s)
    clean, ranges = _split_bold(protected)
    if ranges is None:                       # непарные `**` — работаем как есть
        clean, ranges = protected, []
    for rx, rep in _COMPILED + _AI_RULES:
        clean, ranges = _sub_tracked(rx, rep, clean, ranges)
    return _restore(_join_bold(clean, ranges), saved)
