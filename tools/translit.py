def _protect(text):
    saved = []

    def sub(m):
        saved.append(m.group(0))
        return '\x02%d\x02' % (len(saved) - 1)

    for name in sorted(KEEP, key=len, reverse=True):
        text = re.sub(re.escape(name) + r'[A-Za-zА-Яа-яёЁ\-]*', sub, text)
    return text, saved


def _restore(text, saved):
    return re.sub(r'\x02(\d+)\x02', lambda m: saved[int(m.group(1))], text)


