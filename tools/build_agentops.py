КЕГЛЬ_КАРТОЧКИ, ЗАЗОР_КАРТОЧЕК = 28, 40


def колонка(подписи, кегль=КЕГЛЬ_КАРТОЧКИ, зазор_букв=26, минимум=200):
    """Ширина колонки ряда иконок — по самим подписям, а не на глаз.

    Считаем шаг между центрами так, чтобы у любой соседней пары остался
    зазор, и проверяем, что крайние подписи не выходят к краю кадра.
    """
    if len(подписи) < 2:
        return int(max(минимум, ШРИФТ.ширина(подписи[0], кегль))) - ЗАЗОР_КАРТОЧЕК
    w = [ШРИФТ.ширина(т.replace("&amp;", "&"), кегль) for т in подписи]
    шаг = max(минимум, max((w[i] + w[i + 1]) / 2.0 + зазор_букв for i in range(len(w) - 1)))
    поле = 540 - шаг * (len(w) - 1) / 2.0 - max(w[0], w[-1]) / 2.0
    assert поле >= 60, "ряд иконок не влезает в кадр: %r (поле %d)" % (подписи, поле)
    return int(round(шаг)) - ЗАЗОР_КАРТОЧЕК


