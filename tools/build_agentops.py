def пара(sid, in_, out_, левый, правый, фразы="", комментарий=""):
    """Два элемента над картинами: между ними в кадре голова.

    Если строка-подпись звучит РАНЬШЕ самих элементов, она встаёт сверху:
    так же, как заголовок в рядах иконок. Вывод, который звучит после, —
    снизу, как во всех прошлых роликах.
    """
    сверху = False
    if фразы:
        первая = min(float(x) for x in re.findall(r'class="core [^"]*" data-in="([\d.]+)"', фразы))
        сверху = первая < min(float(левый[0]), float(правый[0]))
    т = ['        <!-- ══ %s ══ -->\n' % (комментарий or sid),
         '        <section class="scene" id="%s" data-in="%s" data-out="%s">\n' % (sid, in_, out_),
         '            <div class="cards">\n' if сверху else '',
         фразы if сверху else '',
         '            <div class="row duo">\n',
         item(левый[0], левый[1], левый[2], 108, левый[3], cur=левый[4]),
         item(правый[0], правый[1], правый[2], 108, правый[3], cur=правый[4]),
         '            </div>\n']
    if фразы and not сверху:
        т.append(фразы)
    if сверху:
        т.append('            </div>\n')
    т.append('        </section>\n\n')
    return "".join(т)


