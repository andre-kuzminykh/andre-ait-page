# -*- coding: utf-8 -*-
"""Совпадает ли ТЕКСТ элемента с тем, что звучит в этот момент.

align7.py ловит только «элемент вышел в тишине». Владелец же поймал
другое: элемент вышел в речи, но не в СВОЕЙ — дорожка оказалась от
другого дубля, и всё ехало на две секунды. Поэтому проверяем по словам:
у каждого элемента берём его собственные слова (корни в 5 букв) и ищем
их в речи вокруг появления.
"""
import re
import sys

# Папку ролика передаём аргументом:
#   python3 tools/проверки/слова.py automation/1/<папка ролика>
ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
ДО, ПОСЛЕ = 1.0, 2.2      # окно вокруг появления, где ищем слово
КОРЕНЬ = 5

СИНОНИМЫ = {                      # слово в кадре → как оно звучит
    "ии": "ai", "ии-процессы": "ai-процессы", "ии-стратегия": "ai-стратегию",
    "четыре": "4", "a/b-тестирование": "a-b",
}
КОРОТКИЕ = {"hr", "ai", "api"}    # слова короче трёх букв, но значащие
СТОП = set("""и в на с а не но или для к по от до за из о об у же то это как
что чем чему все всё их его её ещё уже там тут был была было были есть
""".split())


def реплики():
    out = []
    текст = open(ROOT + "/субтитры.srt", encoding="utf-8-sig").read().replace("\r", "")
    for b in re.split(r"\n\n+", текст.strip()):
        m = re.search(r"(\d\d):(\d\d):(\d\d),(\d\d\d)\s*-->\s*(\d\d):(\d\d):(\d\d),(\d\d\d)", b)
        if not m:
            continue
        г = [int(x) for x in m.groups()]
        a = г[0] * 3600 + г[1] * 60 + г[2] + г[3] / 1000.0
        e = г[4] * 3600 + г[5] * 60 + г[6] + г[7] / 1000.0
        t = " ".join(l for l in b.split("\n") if "-->" not in l and not l.strip().isdigit())
        out.append((a, e, t.strip()))
    return out


РЕЧЬ = реплики()


def речь_вокруг(t):
    куски = [x[2] for x in РЕЧЬ if x[1] > t - ДО and x[0] < t + ПОСЛЕ]
    return " ".join(куски)


def корни(текст):
    # дефис РАЗБИВАЕМ: «A/B-тестирование» в кадре и «A-B тестирование»
    # в речи — одно и то же слово, а как единый токен они не совпадали.
    слова = re.findall(r"\w+", текст.lower().replace("/", "-"), re.U)
    из = []
    for с in слова:
        с = СИНОНИМЫ.get(с, с)
        if с in СТОП or (len(с) < 3 and с not in КОРОТКИЕ):
            continue
        из.append(с[:КОРЕНЬ])
    return из


# Элементы, которые НАРОЧНО не совпадают со словами: карта-итог, где всё
# показано разом, названия этапов из будущего и т.п. Список лежит рядом с
# роликом в «слова-исключения.txt», по строке на текст элемента, комментарии
# после #. Без файла список пуст — и это правильное умолчание: молчаливых
# исключений быть не должно.
ИСКЛЮЧЕНИЯ = set()
try:
    for строка in open(ROOT + "/слова-исключения.txt", encoding="utf-8"):
        строка = строка.split("#")[0].strip()
        if строка:
            ИСКЛЮЧЕНИЯ.add(строка)
except IOError:
    pass

html = open(ROOT + "/index.html", encoding="utf-8").read()
слой = html[html.index('<div id="layer">'):html.index('<div id="cover">')]

плохо = 0
for сцена in re.finditer(r'<section class="scene" id="(\w+)"[^>]*>(.*?)</section>', слой, re.S):
    ид, тело = сцена.group(1), сцена.group(2)
    for m in re.finditer(
            r'<(?:p|div)[^>]*class="(?:item el|label|core|chip|sub|title)[^"]*"[^>]*data-in="([\d.]+)"[^>]*>'
            r'(?:.*?)?</(?:p|div)>|'
            r'<div class="item el"[^>]*data-in="([\d.]+)"[^>]*>.*?<p class="label">(.*?)</p>',
            тело, re.S):
        pass

# проще и надёжнее: собираем пары (время, текст) отдельно по типам
пары = []
for m in re.finditer(r'<div class="(?:item|head) el"[^>]*data-in="([\d.]+)"[^>]*>(.*?)(?=<div class="(?:item|head) el"|</section>|<div class="chips">)',
                     слой, re.S):
    кусок = m.group(2)
    подпись = re.search(r'<p class="(?:label|title)">(.*?)</p>', кусок)
    if подпись:
        пары.append((float(m.group(1)), подпись.group(1), "заголовок"))
    для_sub = re.search(r'<p class="sub el" data-in="([\d.]+)">(.*?)</p>', кусок)
    if для_sub:
        пары.append((float(для_sub.group(1)), для_sub.group(2), "подпись"))
for m in re.finditer(r'<p class="chip [^"]*"[^>]*data-in="([\d.]+)"[^>]*>(.*?)</p>', слой):
    пары.append((float(m.group(1)), m.group(2), "подсказка"))
for m in re.finditer(r'<p class="core [^"]*"[^>]*data-in="([\d.]+)"[^>]*>(.*?)</p>', слой):
    пары.append((float(m.group(1)), m.group(2), "вывод"))

пары.sort()
for t, текст, вид in пары:
    речь = речь_вокруг(t)
    сказано = корни(речь)
    свои = корни(текст)
    попал = [к for к in свои if к in сказано]
    если_можно = текст in ИСКЛЮЧЕНИЯ
    метка = "" if попал else ("   ← нарочно (в исключениях)" if если_можно
                              else "   ← НЕ СОВПАДАЕТ")
    if not попал and not если_можно:
        плохо += 1
    print("%6.2f  %-10s %-32s | %s%s" % (t, вид, текст[:32], речь[:70], метка))

print("\nэлементов: %d, без совпадения со словом: %d" % (len(пары), плохо))
sys.exit(1 if плохо else 0)
