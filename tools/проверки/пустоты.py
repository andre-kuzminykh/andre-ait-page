# -*- coding: utf-8 -*-
"""Графика держится до следующей сцены — пустого кадра между ними нет.

Владелец: «ты просто бросаешь инфографику — надо чтобы она оставалась,
пока не появляется новая».

Почему это видно глазом: сцена гаснет за 0.55 c, а следующая приходит
только со своего data-in. Если между ними зазор хоть в полсекунды, в
кадре остаётся одна шапка — и ролик выглядит рваным. Лечится тем, что
конец сцены равен началу следующей: старая уходит ровно тогда, когда
появляется новая.

Читает разметку, браузер не нужен:
    python3 tools/проверки/пустоты.py automation/1/<папка ролика>
"""
import re
import sys

ПАПКА = sys.argv[1] if len(sys.argv) > 1 else "."
ЗАЗОР = 0.01          # столько считаем «встык»: числа в разметке округлены

html = open(ПАПКА + "/index.html", encoding="utf-8").read()
слой = html[html.index('<div id="layer">'):html.index('<div id="cover">')]

сцены = [(m.group(1), float(m.group(2)), float(m.group(3))) for m in re.finditer(
    r'<section class="scene" id="(\w+)"[^>]*data-in="([\d.]+)"[^>]*data-out="([\d.]+)"', слой)]
assert сцены, "в слое нет ни одной сцены"

пусто, дыр = 0.0, 0
for a, b in zip(сцены, сцены[1:]):
    щель = b[1] - a[2]
    if щель > ЗАЗОР:
        дыр += 1
        пусто += щель
        print("  ✗ %-4s кончается %6.2f, %-4s начинается %6.2f — пустой кадр %.2f c"
              % (a[0], a[2], b[0], b[1], щель))
    elif щель < -0.6:
        print("  · %-4s и %-4s наложены на %.2f c (перекрытие длиннее перехода)"
              % (a[0], b[0], -щель))

print("сцен: %d, дыр: %d, пустого кадра: %.2f c" % (len(сцены), дыр, пусто))
sys.exit(1 if дыр else 0)
