# -*- coding: utf-8 -*-
"""Два кружка в кадре стоят широкой парой, а не рядом посередине.

Владелец: «иконки, когда их две, на одном расстоянии должно быть как
„процессы / структура“ на первом кадре или „бизнес / экономика“».

Почему это важно: между двумя элементами в кадре находится ГОЛОВА
говорящего. Ряд из двух сдвигает обе иконки к центру — прямо на неё, —
и кадр перестаёт работать. Широкая пара (`.row.duo`) ставит каждый
элемент над своей картиной и оставляет середину свободной.

Читает разметку, браузер не нужен:
    python3 tools/проверки/пары.py automation/1/<папка ролика>
"""
import re
import sys

ПАПКА = sys.argv[1] if len(sys.argv) > 1 else "."
html = open(ПАПКА + "/index.html", encoding="utf-8").read()
слой = html[html.index('<div id="layer">'):html.index('<div id="cover">')]

плохо = 0
пар = 0
for m in re.finditer(r'<section class="scene" id="(\w+)"[^>]*>(.*?)</section>', слой, re.S):
    ид, тело = m.group(1), m.group(2)
    # кружки кольца лежат в .cycle и живут по своим правилам круга
    if 'class="cycle"' in тело:
        continue
    кружков = len(re.findall(r'<div class="item el"', тело))
    if кружков != 2:
        continue
    подписи = re.findall(r'<p class="label">(.*?)</p>', тело)
    if 'class="row duo"' in тело:
        пар += 1
        print("  ✓ %-4s %s" % (ид, " ↔ ".join(подписи)))
    else:
        плохо += 1
        print("  ✗ %-4s %s — два кружка рядом посередине, нужна широкая пара"
              % (ид, " ↔ ".join(подписи)))

print("широких пар: %d, сцен с двумя кружками не парой: %d" % (пар, плохо))
sys.exit(1 if плохо else 0)
