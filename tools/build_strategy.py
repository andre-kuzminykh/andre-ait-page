def fly(in_, цвет, значок, сторона, место):
    знак = -1 if сторона == "l" else 1
    доля = max(0.0, min(1.0, место / 214.0))
    траектории = РАЗЛЁТ if доля >= 0.55 else ВВЕРХ
    куски = []
    for dx, dy, rot, задержка in траектории:
        if траектории is РАЗЛЁТ:
            dx = int(dx * доля)
        куски.append('<i style="--dx:%dpx;--dy:%dpx;--rot:%ddeg;animation-delay:%.2fs">%s</i>'
                     % (знак * dx, dy, знак * rot, задержка, ico(значок)))
    return '<span class="fly %s %s el" data-in="%s">%s</span>' % (цвет, сторона, in_, "".join(куски))


ПОЛОСА_ЧИПОВ = 900       # ширина, дальше ряд не помещается в кадр
КЕГЛЬ_ЧИПА, ЗАЗОР_ЧИПОВ = 28, 34


def разложить(чипы):
    """Ряды подсказок набираются по ШИРИНЕ, а не по счёту: три длинных
    слова занимают 1409px и в кадр 988 не влезают, а четыре коротких —
    влезают спокойно. Жадно набираем ряд, пока помещается."""
    ряды, текущий, ширина = [], [], 0.0
    for чип in чипы:
        w = ШРИФТ.ширина(чип[1], КЕГЛЬ_ЧИПА)
        добавка = w + (ЗАЗОР_ЧИПОВ if текущий else 0)
        if текущий and ширина + добавка > ПОЛОСА_ЧИПОВ:
            ряды.append(текущий); текущий, ширина = [], 0.0
            добавка = w
        текущий.append(чип); ширина += добавка
    if текущий:
        ряды.append(текущий)
    assert len(ряды) <= 2, "подсказки не влезают в два ряда: %r" % [c[1] for c in чипы]
    return ряды


def блок(sid, in_, out_, icon, colour, подпись, шапка, шапка_cur, чипы, фразы=""):
    """Слово, сияние за ним, значки по бокам и ряд коротких слов снизу."""
    цвета = ["ember" if colour == "solar" else "solar", colour]
    т = ['        <!-- ══ %s ══ -->\n' % подпись,
         '        <section class="scene" id="%s" data-in="%s" data-out="%s">\n' % (sid, in_, out_),
         '            <div class="block">\n',
         '                <div class="head el"%s>'
         '<div class="halo"><div class="glow %s" style="width:%dpx"></div></div>%s'
         '<p class="title">%s</p>%s</div>\n'
         % (атрибуты(шапка, cur=шапка_cur), "glow-ember" if colour == "ember" else "",
            сияние(подпись), fly(шапка, colour, icon, "l", запас(подпись)), подпись,
            fly(шапка, colour, icon, "r", запас(подпись))),
         '                <div class="chips">\n']
    ряды = разложить(чипы)
    н = 0
    for ряд in ряды:
        т.append('                    <div class="line">\n')
        for t, текст, окно in ряд:
            т.append('                        <p class="chip %s el"%s>%s</p>\n'
                     % (цвета[н % 2], атрибуты(t, cur=окно), текст))
            н += 1
        т.append('                    </div>\n')
    т.append('                </div>\n')
    if фразы:
        т.append(фразы)
    т.append('            </div>\n        </section>\n\n')
    return "".join(т)


