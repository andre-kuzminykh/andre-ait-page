def сияние(подпись):
    """Ширина облака за заголовком — по ширине слова, а не одна на всех."""
    w = ШРИФТ.ширина(подпись.replace("&amp;", "&"), КЕГЛЬ_ЗАГОЛОВКА)
    return int(max(520, min(900, w + 280)))


