def сияние(подпись):
    """Ширина облака за заголовком — по ширине слова, а не одна на всех."""
    w = ШРИФТ.ширина(подпись.replace("&amp;", "&"), КЕГЛЬ_ЗАГОЛОВКА)
    return int(max(520, min(900, w + 280)))


КЕГЛЬ_ТРИО, ЗАЗОР_ТРИО = 30, 40


def трио(подписи, кегль=КЕГЛЬ_ТРИО, зазор_букв=24):
    """Ширина колонки для ряда из трёх подписей — по буквам, а не на глаз.

    Подписи стоят `nowrap` и вылезают из своей колонки: «Поддерживающие»
    и «Управленческие» кеглем 30 сходились буква к букве. Считаем шаг
    между центрами так, чтобы у любой соседней пары остался зазор, и
    возвращаем ширину `.item` (шаг минус ряд-gap).
    """
    w = [ШРИФТ.ширина(т.replace("&amp;", "&"), кегль) for т in подписи]
    шаг = max((w[i] + w[i + 1]) / 2.0 + зазор_букв for i in range(len(w) - 1))
    поле = 540 - шаг - max(w[0], w[-1]) / 2.0
    assert поле >= 60, "ряд не влезает в кадр: %r (поле %d)" % (подписи, поле)
    return int(round(шаг)) - ЗАЗОР_ТРИО


