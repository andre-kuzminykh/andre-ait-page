РАЗЛЁТ = [(104, -50, -14, 0.00), (132, -78, 10, 0.28),
          (166, 12, 12, 0.55), (214, -24, -8, 1.10)]
# Веер вверх: сбоку места нет, поэтому значки идут лесенкой ВВЕРХ.
# Отступ вбок задан ДОЛЕЙ от свободного места — иначе у самого широкого
