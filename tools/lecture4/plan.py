def source_for(num):
    blob = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "source.md"),
                   encoding="utf-8").read()
    m = re.search(r"^## %s\..*?(?=^## |\Z)" % re.escape(num), blob, re.S | re.M)
    if not m:
        raise SystemExit("нет исходного текста для %s" % num)
    return m.group(0).strip()


